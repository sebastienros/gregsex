#nullable enable
using System.ComponentModel;
using System.Diagnostics.CodeAnalysis;
using GregsEx.Contracts.Acceleration;
using GregsEx.Execution.Compiled;
using GregsEx.Flavors.Oniguruma;

namespace GregsEx;

/// <summary>An immutable Oniguruma pattern; share it across threads and create a workspace per thread.</summary>
public sealed class OnigurumaPattern
{
    internal OnigProgram Program { get; }

    internal RegexMatchLimits MatchLimits { get; }

    // The pattern text and compile options, which the kernel planner re-analyses.
    internal string Source { get; }
    internal OnigurumaCompileOptions CompileOptions { get; }

    // Lowered kernels (Compile or the source generator), or null: the interpreter then serves every search.
    internal CoreKernel? PlainKernel { get; }
    internal CoreKernel? CaptureKernel { get; }
    private readonly CompiledKernelBudget.Lease? _lease;

    /// <summary>The syntax and data identity.</summary>
    public OnigurumaProfile Profile { get; }

    /// <summary>The number of captures including group zero.</summary>
    public int GroupCount => Program.GroupCount;

    /// <summary>Whether searches run generated code (after <see cref="Compile"/> or from the source generator) or the interpreter.</summary>
    public RegexExecutionBackend ExecutionBackend => PlainKernel is null ? RegexExecutionBackend.Interpreted : RegexExecutionBackend.Compiled;

    private OnigurumaPattern(OnigProgram program, OnigurumaProfile profile, string source, OnigurumaCompileOptions options)
    {
        Program = program;
        Profile = profile;
        Source = source;
        CompileOptions = options;
        MatchLimits = options.DefaultMatchLimits;
    }

    private OnigurumaPattern(OnigurumaPattern source, CoreKernel plain, CoreKernel capture, CompiledKernelBudget.Lease? lease)
    {
        Program = source.Program;
        Profile = source.Profile;
        Source = source.Source;
        CompileOptions = source.CompileOptions;
        MatchLimits = source.MatchLimits;
        PlainKernel = plain;
        CaptureKernel = capture;
        _lease = lease;
    }

    /// <summary>
    /// Returns an immutable pattern whose matching loop is generated code. Results, captures and limits equal the
    /// interpreter's; subjects the generated code does not model (surrogates) and searches with options fall back to it.
    /// </summary>
    /// <exception cref="PlatformNotSupportedException">The runtime cannot generate code.</exception>
    /// <exception cref="NotSupportedException">The pattern uses a construct the lowering does not model or exceeds its bounds.</exception>
    [RequiresDynamicCode(CompilationContract.RequiresDynamicCodeMessage)]
    [RequiresUnreferencedCode(CompilationContract.RequiresUnreferencedCodeMessage)]
    public OnigurumaPattern Compile()
    {
        if (!CompilationContract.IsRuntimeCompilationAvailable)
        {
            throw new PlatformNotSupportedException(CompilationContract.RequiresDynamicCodeMessage);
        }

        if (PlainKernel is not null)
        {
            return this;
        }

        if (!OnigCompiledSearch.TryCompile(this, out var plain, out var capture, out var lease, out var reason))
        {
            throw new NotSupportedException(reason);
        }

        return new(this, plain!, capture!, lease);
    }

    /// <summary>
    /// Wraps kernels emitted by the GregsEx source generator, as <see cref="Compile"/> would. The kernels must have been
    /// generated for this exact pattern and profile; the source generator guarantees that, and a kernel generated by a
    /// different generator/library revision is ignored (the interpreted pattern is returned). Needs no runtime code
    /// generation and is compatible with trimming and NativeAOT.
    /// </summary>
    /// <exception cref="NotSupportedException">The pattern already has compiled kernels.</exception>
    [EditorBrowsable(EditorBrowsableState.Never)]
    public OnigurumaPattern WithGeneratedKernels(ulong fingerprint, CoreKernel plain, CoreKernel capture)
    {
        ArgumentNullException.ThrowIfNull(plain);
        ArgumentNullException.ThrowIfNull(capture);
        if (PlainKernel is not null)
        {
            throw new NotSupportedException("This pattern already has compiled or generated kernels.");
        }

        if (!OnigKernelPlan.TryPlan(Source, Profile, CompileOptions.Limits, LoweringLimits.Default, out var plan, out _, out _)
            || plan is null || plan.Fingerprint() != fingerprint)
        {
            return this;
        }

        return new(this, plain, capture, null);
    }

    /// <summary>Parses a pattern, throwing <see cref="RegexParseException"/> on a diagnostic.</summary>
    public static OnigurumaPattern Parse(string pattern, OnigurumaProfile? profile = null, OnigurumaCompileOptions? options = null)
    {
        ArgumentNullException.ThrowIfNull(pattern);
        if (!TryParse(pattern, profile ?? RegexProfiles.Oniguruma, out var result, out var diagnostic, options))
        {
            throw new RegexParseException(diagnostic);
        }

        return result!;
    }

    /// <summary>Parses UTF-16 pattern units without retaining the borrowed source.</summary>
    public static bool TryParse(ReadOnlySpan<char> pattern, OnigurumaProfile profile, out OnigurumaPattern? result,
        out RegexDiagnostic diagnostic, OnigurumaCompileOptions? options = null)
    {
        ArgumentNullException.ThrowIfNull(profile);
        options ??= new OnigurumaCompileOptions();
        result = null;
        diagnostic = default;
        var flags = profile.Options;
        var inline = OnigInlineOptions.None;
        if ((flags & OnigurumaOptions.IgnoreCase) != 0)
        {
            inline |= OnigInlineOptions.IgnoreCase;
        }

        if ((flags & OnigurumaOptions.Multiline) != 0)
        {
            inline |= OnigInlineOptions.DotAll;
        }

        if ((flags & OnigurumaOptions.Extended) != 0)
        {
            inline |= OnigInlineOptions.Extended;
        }

        try
        {
            var source = pattern.ToString();
            var program = OnigCompiler.Compile(source, inline,
                (flags & OnigurumaOptions.CaptureGroup) != 0, (flags & OnigurumaOptions.DontCaptureGroup) != 0, options.Limits);
            result = new OnigurumaPattern(program, profile, source, options);
            return true;
        }
        catch (OnigSyntaxException e)
        {
            diagnostic = new RegexDiagnostic(e.Code, e.Offset, e.Length, RegexOffsetUnit.Utf16CodeUnits, e.Message);
            return false;
        }
    }

    /// <summary>The group numbers with this name, in pattern order; empty when none.</summary>
    public ReadOnlySpan<int> GetGroupNumbers(ReadOnlySpan<char> name)
    {
        var numbers = new List<int>();
        var names = Program.GroupNames;
        for (var g = 1; g < names.Length; g++)
        {
            if (names[g] is { } n && name.SequenceEqual(n))
            {
                numbers.Add(g);
            }
        }
        return numbers.ToArray();
    }

    /// <summary>The name of a group, or null.</summary>
    public string? GetGroupName(int number)
        => (uint)number < (uint)Program.GroupNames.Length ? Program.GroupNames[number] : null;

    /// <summary>Creates an exclusively owned, reusable workspace.</summary>
    public OnigurumaWorkspace CreateWorkspace() => new(this);

    /// <summary>
    /// Whether the pattern matches anywhere; throws <see cref="RegexExecutionException"/> on a limit. A convenience
    /// that creates a workspace per call: reuse <see cref="CreateWorkspace"/> for repeated searches.
    /// </summary>
    public bool IsMatch(ReadOnlySpan<char> input)
    {
        var status = CreateWorkspace().IsMatch(input);
        if (status == RegexSearchStatus.LimitExceeded)
        {
            throw new RegexExecutionException(new RegexExecutionFailure(RegexExecutionFailureCode.WorkLimitExceeded, 0, 0));
        }

        return status == RegexSearchStatus.Match;
    }
}

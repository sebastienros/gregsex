using System.Text;
using GregsEx.Execution.Compiled;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace GregsEx.Generator;

/// <summary>
/// Turns <c>[GeneratedPattern]</c> partial methods into patterns whose matching loop is C# emitted at build time. The
/// generator runs the real GregsEx parser and kernel planner, so eligibility, benefit rules and semantics are those of
/// <c>RegexPattern.Compile()</c>, but nothing is generated at run time: no dynamic code, no JIT-time memory growth, and it
/// is compatible with trimming and NativeAOT.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class PatternGenerator : IIncrementalGenerator
{
    internal const string AttributeMetadataName = "GregsEx.SourceGeneration.GeneratedPatternAttribute";

    private const string AttributeSource = """
        // <auto-generated/>
        #nullable enable
        namespace GregsEx.SourceGeneration
        {
            /// <summary>The regex flavor of a generated pattern.</summary>
            internal enum GeneratedPatternFlavor { RegularCore, EcmaScript, Xsd, XPath, Pcre2 }

            /// <summary>Marks a <c>static partial RegexPattern Name();</c> method whose pattern is compiled at build time.</summary>
            [global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = false, Inherited = false)]
            internal sealed class GeneratedPatternAttribute : global::System.Attribute
            {
                public GeneratedPatternAttribute(string pattern, global::GregsEx.RegularCoreFlags flags = global::GregsEx.RegularCoreFlags.None) { }
                public GeneratedPatternAttribute(string pattern, global::GregsEx.EcmaScriptFlags flags) { }
                public GeneratedPatternAttribute(string pattern, global::GregsEx.XPathFlags flags) { }
                public GeneratedPatternAttribute(string pattern, global::GregsEx.Pcre2CompileFlags flags) { }
                public GeneratedPatternAttribute(string pattern, GeneratedPatternFlavor flavor) { }
                /// <summary>The Unicode dataset for ECMAScript, XSD, or XPath; defaults to Unicode 16.0.</summary>
                public global::GregsEx.UnicodeVersion UnicodeVersion { get; set; } = global::GregsEx.UnicodeVersion.Unicode16_0;
            }
        }
        """;

    private static readonly DiagnosticDescriptor InvalidPattern = new("GREGEX001", "Invalid generated pattern",
        "The pattern of '{0}' is not valid: {1}", "GregsEx", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor InvalidMethod = new("GREGEX002", "Invalid generated pattern method",
        "'{0}' cannot be a generated pattern: {1}", "GregsEx", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor NotCompiled = new("GREGEX003", "Generated pattern is interpreted",
        "'{0}' runs on the interpreter: {1}", "GregsEx", DiagnosticSeverity.Info, true);
    private static readonly DiagnosticDescriptor InvalidFlags = new("GREGEX004", "Invalid generated pattern flags",
        "The flags of '{0}' are not valid for its flavor: {1}", "GregsEx", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor InvalidUnicodeVersion = new("GREGEX005", "Invalid generated pattern Unicode version",
        "The Unicode version of '{0}' is unsupported for its flavor", "GregsEx", DiagnosticSeverity.Error, true);

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static c => c.AddSource("GregsEx.GeneratedPatternAttribute.g.cs", AttributeSource));
        var specs = context.SyntaxProvider.ForAttributeWithMetadataName(AttributeMetadataName,
            static (node, _) => node is MethodDeclarationSyntax, Transform).WithTrackingName("Specs");
        // Emitted kernels bind .NET 8+ span APIs (SearchValues, IndexOfAnyInRange); older targets such as
        // netstandard2.0 get the interpreted pattern instead, reported through GREGEX003.
        var kernels = context.CompilationProvider.Select(static (compilation, _) =>
            compilation.GetTypeByMetadataName("System.MemoryExtensions")?.GetMembers("IndexOfAnyInRange").Length > 0);
        context.RegisterSourceOutput(specs.Combine(kernels), static (c, pair) => Emit(c, pair.Left, pair.Right));
    }

    private static PatternSpec Transform(GeneratorAttributeSyntaxContext context, System.Threading.CancellationToken cancellationToken)
    {
        var method = (IMethodSymbol)context.TargetSymbol;
        var location = LocationInfo.From(context.TargetNode.GetLocation());
        var attribute = context.Attributes[0];
        var name = method.Name;
        string? error = null;

        if (!method.IsStatic || !method.IsPartialDefinition || method.Parameters.Length != 0 || method.IsGenericMethod
            || method.ReturnType.ToDisplayString() != "GregsEx.RegexPattern")
        {
            error = "it must be declared 'static partial RegexPattern Name();' with no parameters and no type parameters";
        }

        var containers = new List<string>();
        for (var type = method.ContainingType; type is not null && error is null; type = type.ContainingType)
        {
            var keyword = type.TypeKind switch
            {
                TypeKind.Class => type.IsRecord ? "record" : "class",
                TypeKind.Struct => type.IsRecord ? "record struct" : "struct",
                _ => null
            };
            var isPartial = type.DeclaringSyntaxReferences.Any(r => r.GetSyntax(cancellationToken) is TypeDeclarationSyntax t
                && t.Modifiers.Any(m => m.IsKind(Microsoft.CodeAnalysis.CSharp.SyntaxKind.PartialKeyword)));
            if (keyword is null)
            {
                error = $"its containing type '{type.Name}' must be a class or struct";
            }
            else if (!isPartial)
            {
                error = $"its containing type '{type.Name}' must be partial";
            }
            else if (type.IsGenericType)
            {
                error = $"its containing type '{type.Name}' must not be generic";
            }
            else
            {
                containers.Insert(0, $"partial {keyword} {type.Name}");
            }
        }

        var ns = method.ContainingNamespace is { IsGlobalNamespace: false } n ? n.ToDisplayString() : null;
        var accessibility = method.DeclaredAccessibility switch
        {
            Accessibility.Public => "public",
            Accessibility.Internal => "internal",
            Accessibility.Protected => "protected",
            Accessibility.ProtectedOrInternal => "protected internal",
            Accessibility.ProtectedAndInternal => "private protected",
            _ => "private"
        };

        var pattern = string.Empty;
        var flavor = "RegularCore";
        long flags = 0;
        var args = attribute.ConstructorArguments;
        if (args.Length >= 1 && args[0].Value is string text)
        {
            pattern = text;
        }
        else
        {
            error ??= "the pattern must be a constant string";
        }

        if (error is null && attribute.AttributeConstructor is { Parameters.Length: >= 2 } ctor && args.Length >= 2)
        {
            var parameterType = ctor.Parameters[1].Type.Name;
            var value = args[1].Value is null ? 0 : Convert.ToInt64(args[1].Value, System.Globalization.CultureInfo.InvariantCulture);
            switch (parameterType)
            {
                case "RegularCoreFlags":
                    flags = value;
                    break;
                case "EcmaScriptFlags":
                    flavor = "EcmaScript";
                    flags = value;
                    break;
                case "XPathFlags":
                    flavor = "XPath";
                    flags = value;
                    break;
                case "Pcre2CompileFlags":
                    flavor = "Pcre2";
                    flags = value;
                    break;
                case "GeneratedPatternFlavor":
                    flavor = value switch { 1 => "EcmaScript", 2 => "Xsd", 3 => "XPath", 4 => "Pcre2", _ => "RegularCore" };
                    break;
            }
        }
        var unicodeVersion = UnicodeVersion.Unicode16_0;
        foreach (var argument in attribute.NamedArguments)
        {
            if (argument.Key == "UnicodeVersion" && argument.Value.Value is int version)
            {
                unicodeVersion = (UnicodeVersion)version;
            }
        }
        return new PatternSpec(ns, string.Join("\n", containers), name, accessibility, pattern, flavor, flags,
            unicodeVersion, error, location);
    }

    private static void Emit(SourceProductionContext context, PatternSpec spec, bool kernels)
    {
        var location = spec.Location.ToLocation();
        if (spec.Error is not null)
        {
            context.ReportDiagnostic(Diagnostic.Create(InvalidMethod, location, spec.MethodName, spec.Error));
            return;
        }
        if (spec.UnicodeVersion is not (UnicodeVersion.Unicode16_0 or UnicodeVersion.Unicode17_0) ||
            (spec.UnicodeVersion != UnicodeVersion.Unicode16_0 && spec.Flavor is not ("EcmaScript" or "Xsd" or "XPath")))
        {
            context.ReportDiagnostic(Diagnostic.Create(InvalidUnicodeVersion, location, spec.MethodName));
            context.AddSource(HintName(spec), Wrap(spec, FailureMember(spec)));
            return;
        }
        RegexProfile profile;
        string profileCode;
        try
        { profile = CreateProfile(spec, out profileCode); }
        catch (ArgumentOutOfRangeException ex)
        {
            context.ReportDiagnostic(Diagnostic.Create(InvalidFlags, location, spec.MethodName, ex.ParamName ?? "flags"));
            context.AddSource(HintName(spec), Wrap(spec, FailureMember(spec)));
            return;
        }

        RegexDiagnostic diagnostic;
        bool parsed;
        CoreKernelPlan? plan;
        string reason;
        try
        { parsed = SourcePlanner.TryPlan(spec.Pattern, profile, out plan, out reason, out diagnostic); }
        catch (Exception ex) when (ex is not OperationCanceledException)
        {
            plan = null;
            reason = ex.Message;
            diagnostic = new RegexDiagnostic(RegexDiagnosticCode.InvalidSyntax, 0, 0, RegexOffsetUnit.Utf16CodeUnits, ex.Message);
            parsed = false;
        }
        if (!parsed)
        {
            var message = diagnostic.Message ?? diagnostic.Code.ToString();
            context.ReportDiagnostic(Diagnostic.Create(InvalidPattern, location, spec.MethodName,
                $"{message} (code unit offset {diagnostic.Offset})"));
            context.AddSource(HintName(spec), Wrap(spec, FailureMember(spec)));
            return;
        }

        var name = spec.MethodName;
        var members = new StringBuilder();
        var create = $"global::GregsEx.RegexPattern.Parse({KernelEmitter.Lit(spec.Pattern)}, {profileCode}, " +
            "new global::GregsEx.RegexCompileOptions(global::GregsEx.RegexInputKind.Utf16, global::GregsEx.RegexExecutionMode.Auto))";
        members.AppendLine($"private static global::GregsEx.RegexPattern? __GregsEx_{name}_Cache;");
        members.AppendLine($"{spec.Accessibility} static partial global::GregsEx.RegexPattern {name}() => __GregsEx_{name}_Cache ??= __GregsEx_{name}_Create();");

        if (plan is not null && !kernels)
        {
            plan = null;
            reason = "generated kernels require .NET 8 or later";
        }
        if (plan is not null)
        {
            members.AppendLine($"private static global::GregsEx.RegexPattern __GregsEx_{name}_Create() =>");
            var captureClass = plan!.GroupCount > 1 ? $"__GregsEx_{name}_Capture" : $"__GregsEx_{name}_Plain";
            members.AppendLine($"    {create}.WithGeneratedKernels(0x{plan.Fingerprint():X16}UL, __GregsEx_{name}_Plain.Run, {captureClass}.Run);");
            members.AppendLine();
            members.Append(KernelEmitter.EmitClass($"__GregsEx_{name}_Plain", plan, track: false));
            if (plan.GroupCount > 1)
            {
                members.AppendLine();
                members.Append(KernelEmitter.EmitClass($"__GregsEx_{name}_Capture", plan, track: true));
            }
        }
        else
        {
            context.ReportDiagnostic(Diagnostic.Create(NotCompiled, location, name, reason));
            members.AppendLine($"private static global::GregsEx.RegexPattern __GregsEx_{name}_Create() => {create};");
        }
        context.AddSource(HintName(spec), Wrap(spec, members.ToString()));
    }

    private static string FailureMember(PatternSpec spec) =>
        $"{spec.Accessibility} static partial global::GregsEx.RegexPattern {spec.MethodName}() => throw new global::System.InvalidOperationException(\"The generated pattern is invalid.\");\n";

    private static RegexProfile CreateProfile(PatternSpec spec, out string code)
    {
        // Constants are re-validated by the profile constructors, so out-of-range bits become a diagnostic, not bad code.
        var f = spec.Flags.ToString(System.Globalization.CultureInfo.InvariantCulture);
        var version = $"global::GregsEx.UnicodeVersion.{spec.UnicodeVersion}";
        switch (spec.Flavor)
        {
            case "EcmaScript":
                code = $"new global::GregsEx.EcmaScriptProfile(unchecked((global::GregsEx.EcmaScriptFlags){f}), {version})";
                return new EcmaScriptProfile(unchecked((EcmaScriptFlags)spec.Flags), spec.UnicodeVersion);
            case "Xsd":
                code = $"new global::GregsEx.XsdProfile({version})";
                return new XsdProfile(spec.UnicodeVersion);
            case "XPath":
                code = $"new global::GregsEx.XPathProfile(unchecked((global::GregsEx.XPathFlags){f}), {version})";
                return new XPathProfile(unchecked((XPathFlags)spec.Flags), spec.UnicodeVersion);
            case "Pcre2":
                code = $"new global::GregsEx.Pcre2Profile(global::GregsEx.Pcre2CodeUnitWidth.Sixteen, unchecked((global::GregsEx.Pcre2CompileFlags){f}))";
                return new Pcre2Profile(Pcre2CodeUnitWidth.Sixteen, unchecked((Pcre2CompileFlags)spec.Flags));
            default:
                code = $"new global::GregsEx.RegularCoreProfile(global::GregsEx.RegularCoreMode.UnicodeScalars, unchecked((global::GregsEx.RegularCoreFlags){f}))";
                return new RegularCoreProfile(RegularCoreMode.UnicodeScalars, unchecked((RegularCoreFlags)spec.Flags));
        }
    }

    private static string HintName(PatternSpec spec)
    {
        using var sb = new GregsEx.Text.ValueStringBuilder();
        if (spec.Namespace is not null)
        {
            sb.Append(spec.Namespace);
            sb.Append('.');
        }

        foreach (var container in spec.Containers.Split('\n'))
        {
            if (container.Length > 0)
            {
                sb.Append(container.AsSpan(container.LastIndexOf(' ') + 1));
                sb.Append('.');
            }
        }

        sb.Append(spec.MethodName);
        sb.Append(".g.cs");
        return sb.ToString();
    }

    private static string Wrap(PatternSpec spec, string members)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable");
        var depth = 0;
        void Line(string text) => sb.AppendLine(text.Length == 0 ? text : new string(' ', depth * 4) + text);
        if (spec.Namespace is not null)
        { Line($"namespace {spec.Namespace}"); Line("{"); depth++; }
        foreach (var container in spec.Containers.Split('\n'))
        {
            if (container.Length > 0)
            { Line(container); Line("{"); depth++; }
        }

        foreach (var line in members.Replace("\r\n", "\n").TrimEnd('\n').Split('\n'))
        {
            Line(line);
        }

        while (depth > 0)
        { depth--; Line("}"); }
        return sb.ToString();
    }

    internal sealed record PatternSpec(string? Namespace, string Containers, string MethodName, string Accessibility,
        string Pattern, string Flavor, long Flags, UnicodeVersion UnicodeVersion, string? Error, LocationInfo Location);

    internal sealed record LocationInfo(string Path, TextSpan Span, LinePositionSpan Lines)
    {
        internal static LocationInfo From(Location location) =>
            new(location.SourceTree?.FilePath ?? string.Empty, location.SourceSpan, location.GetLineSpan().Span);

        internal Location ToLocation() => Location.Create(Path, Span, Lines);
    }
}

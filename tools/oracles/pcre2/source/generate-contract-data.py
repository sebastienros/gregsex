"""Project enums/default low-byte data from the retained, hash-verified header."""
import hashlib
import json
from pathlib import Path
import re
import tarfile

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parents[3]
manifest = json.loads((ROOT / 'source-manifest.json').read_text())
with tarfile.open(ROOT / 'pcre2-10.46-source.tar.gz') as archive:
    def read(path):
        data = archive.extractfile('pcre2-pcre2-10.46/' + path).read()
        record = next(item for item in manifest['files'] if item['path'] == path)
        assert hashlib.sha256(data).hexdigest() == record['sha256']
        return data.decode()
    header = read('src/pcre2.h.generic')
    chartables = read('src/pcre2_chartables.c.dist')
    license_text = read('LICENCE.md')
    ucp = read('src/pcre2_ucp.h')

definitions = {}
for name, value in re.findall(r'^#define (PCRE2_\w+)\s+([^\n]+)', header, re.M):
    value = value.split('/*')[0].strip().strip('()').rstrip('u')
    try:
        definitions[name] = int(value, 0)
    except ValueError:
        pass

def member(name):
    return ''.join(word.capitalize() for word in name.split('_'))

output = ['#nullable enable', '// Generated by tools/oracles/pcre2/source/generate-contract-data.py.',
          '// Native constants: PCRE2 10.46 b2bd4254; BSD notice in PCRE2-NOTICE.txt.',
          'namespace GregsEx;', '']
groups = [
    ('Pcre2CompileFlags', [name for name in definitions if name in ('PCRE2_ANCHORED', 'PCRE2_ENDANCHORED', 'PCRE2_NO_UTF_CHECK') or
      name.removeprefix('PCRE2_') in ('ALLOW_EMPTY_CLASS','ALT_BSUX','AUTO_CALLOUT','CASELESS','DOLLAR_ENDONLY','DOTALL','DUPNAMES','EXTENDED','FIRSTLINE','MATCH_UNSET_BACKREF','MULTILINE','NEVER_UCP','NEVER_UTF','NO_AUTO_CAPTURE','NO_AUTO_POSSESS','NO_DOTSTAR_ANCHOR','NO_START_OPTIMIZE','UCP','UNGREEDY','UTF','NEVER_BACKSLASH_C','ALT_CIRCUMFLEX','ALT_VERBNAMES','USE_OFFSET_LIMIT','EXTENDED_MORE','LITERAL','MATCH_INVALID_UTF','ALT_EXTENDED_CLASS')], 'PCRE2_', True),
    ('Pcre2ExtraFlags', [name for name in definitions if name.startswith('PCRE2_EXTRA_')], 'PCRE2_EXTRA_', True),
    ('Pcre2MatchFlags', [name for name in definitions if name.removeprefix('PCRE2_') in ('ANCHORED','ENDANCHORED','NO_UTF_CHECK','NOTBOL','NOTEOL','NOTEMPTY','NOTEMPTY_ATSTART','PARTIAL_SOFT','PARTIAL_HARD','NO_JIT','COPY_MATCHED_SUBJECT','DISABLE_RECURSELOOP_CHECK')], 'PCRE2_', True),
    ('Pcre2SubstituteFlags', [name for name in definitions if name.startswith('PCRE2_SUBSTITUTE_') and '_CASE_' not in name], 'PCRE2_SUBSTITUTE_', True),
    ('Pcre2Newline', [name for name in definitions if name.startswith('PCRE2_NEWLINE_')], 'PCRE2_NEWLINE_', False),
    ('Pcre2Bsr', [name for name in definitions if name.startswith('PCRE2_BSR_')], 'PCRE2_BSR_', False),
    ('Pcre2CalloutFlags', [name for name in definitions if name.startswith('PCRE2_CALLOUT_')], 'PCRE2_CALLOUT_', True),
    ('Pcre2SubstituteCase', [name for name in definitions if name.startswith('PCRE2_SUBSTITUTE_CASE_')], 'PCRE2_SUBSTITUTE_CASE_', False),
    ('Pcre2ErrorCode', [name for name in definitions if name.startswith('PCRE2_ERROR_')], 'PCRE2_ERROR_', False),
    ('Pcre2PatternInfoKey', [name for name in definitions if name.startswith('PCRE2_INFO_')], 'PCRE2_INFO_', False)
]
for enum, names, prefix, flags in groups:
    output += [f'/// <summary>Pinned native {enum} identities; admitted combinations follow the PCRE2 profile contract.</summary>']
    if flags:
        output.append('[Flags]')
    output.append(f'public enum {enum}' + (' : uint' if flags else '') + '\n{')
    if flags or enum == 'Pcre2ErrorCode':
        output += ['    /// <summary>No flags or no source error.</summary>', '    None = 0,']
    for name in names:
        value = definitions[name]
        output += [f'    /// <summary>{name} ({value}); source-defined native identity, not an implementation claim.</summary>',
                   f'    {member(name.removeprefix(prefix))} = ' + (f'0x{value:08X}u' if flags else str(value)) + ',']
    output += ['}', '']
(REPO / 'src/GregsEx/Public/Pcre2/Pcre2Enums.cs').write_text('\n'.join(output))

body = chartables.split('PRIV(default_tables)[] = {', 1)[1].split('};',1)[0]
body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
values = [int(number, 0) if number.startswith('0x') else int(number)
          for number in re.findall(r'0x[\da-fA-F]+|\d+', body)]
assert len(values) == 1088 and all(0 <= value <= 255 for value in values)
data = bytes(values)
digest = hashlib.sha256(data).hexdigest()
rows = [', '.join(str(value) for value in values[start:start+32]) for start in range(0,len(values),32)]
generated = '#nullable enable\n// Pinned PCRE2 C-locale data; source BSD notice in Public/Pcre2/PCRE2-NOTICE.txt.\nnamespace GregsEx.Contracts.Pcre2;\n\ninternal static class Pcre2DefaultTables\n{\n'
generated += f'    internal const string Digest = "{digest}";\n'
generated += '    internal static ReadOnlySpan<byte> Bytes => [\n        ' + ',\n        '.join(rows) + '\n    ];\n}\n'
(REPO / 'src/GregsEx/Contracts/Pcre2/Pcre2DefaultTables.cs').write_text(generated)
(REPO / 'src/GregsEx/Public/Pcre2/PCRE2-NOTICE.txt').write_text(
    'Pinned PCRE2 10.46 native constants and default C-locale character tables.\n'
    'Source: b2bd4254b379b9d7dc9a3dda060a7e27009ccdff.\n'
    'This notice does not claim that a PCRE2 engine or native library is distributed.\n\n' + license_text)
ucp_output=['#nullable enable', '// Pinned PCRE2 Unicode ID namespaces; BSD notice in Public/Pcre2/PCRE2-NOTICE.txt.',
            'namespace GregsEx.Contracts.Pcre2;','']
enum_names=['Pcre2MajorCategory','Pcre2ParticularCategory','Pcre2BooleanProperty','Pcre2BidiClass','Pcre2GraphemeBreak','Pcre2Script']
for enum_name,body in zip(enum_names,re.findall(r'enum\s*{(.*?)};',ucp,re.S),strict=True):
    names=re.findall(r'\bucp_\w+',re.sub(r'/\*.*?\*/','',body,flags=re.S))
    ucp_output.append(f'internal enum {enum_name}\n{{')
    for index,name in enumerate(names):
        ucp_output.append(f'    {name.removeprefix("ucp_")} = {index},')
    ucp_output.extend(['}',''])
ucp_output.append('''internal static class Pcre2DataAbi
{
    internal const int BlockSize=128;
    internal const int ScriptWords=6;
    internal const int BooleanWords=2;
    internal const int LowerOffset=0,FlipOffset=256,ClassOffset=512,TypeOffset=832;
    internal static bool IsValidProperty(Pcre2PropertyKey key)=>key.Kind switch
    {
        Pcre2PropertyKind.MajorCategory=>key.Id is>=0 and<7,
        Pcre2PropertyKind.ParticularCategory=>key.Id is>=0 and<30,
        Pcre2PropertyKind.Script or Pcre2PropertyKind.ScriptExtensions=>key.Id is>=0 and<171,
        Pcre2PropertyKind.Binary=>key.Id is>=0 and<57,
        Pcre2PropertyKind.BidiClass=>key.Id is>=0 and<23,
        Pcre2PropertyKind.Special=>key.Id is 0 or 5 or 6 or 7 or 8 or 10 or 13 or 14 or 15 or 16 or 17,
        _=>false
    };
}''')
(REPO/'src/GregsEx/Contracts/Pcre2/Pcre2DataAbi.cs').write_text('\n'.join(ucp_output)+'\n')
print('Generated10 enum groups and1088 default-table bytes; table SHA256',digest)

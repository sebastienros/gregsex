"""Supplementary HASBACKSLASHC oracle; preserves the earlier J-only intake.

Run from repo root: python3 tools/oracles/pcre2/option-metadata/probe-c.py
"""
import hashlib
import json
from pathlib import Path
import subprocess
import tarfile

REPORT = Path("test/corpora/pcre2/option-metadata")
HERE = Path(__file__).resolve().parent
TEMP = Path("/private/tmp/gregsex-m5-option-metadata-native")
TEMP.mkdir(parents=True, exist_ok=True)
hashes = {}
def digest(data):
    return hashlib.sha256(data).hexdigest()

receipt = json.loads(Path("test/corpora/pcre2/controls/native-window-provenance.json").read_text())
archive = Path(receipt["archive"])
assert digest(archive.read_bytes()) == receipt["archiveSha256"]
hashes[str(archive)] = receipt["archiveSha256"]
with tarfile.open(archive) as tar:
    for row in receipt["members"]:
        data = tar.extractfile(row["member"]).read()
        assert len(data) == row["bytes"] and digest(data) == row["sha256"]
        path = TEMP / row["member"]
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        hashes[row["member"]] = digest(data)
source = Path("tools/oracles/pcre2/source/pcre2-10.46-source.tar.gz")
assert digest(source.read_bytes()) == "ffde0c6ead457c4f8edcd8f9ce490bbabd30adabdfd179ecaddd320946cf3872"
hashes[str(source)] = digest(source.read_bytes())
with tarfile.open(source) as tar:
    member = "pcre2-pcre2-10.46/src/pcre2_compile.c"
    data = tar.extractfile(member).read()
    hashes[member] = digest(data)
    lines = data.decode().splitlines()
    (REPORT / "source-c-witness.txt").write_text("\n".join(
        f"{i+1}: {lines[i]}" for i in range(8105, 8123)) + "\n")

UTF = 0x80000
LITERAL = 0x2000000
NEVER_C = 0x100000
seeds = [
    ("c", r"\C", 0), ("c-zero", r"\C{0}", 0),
    ("c-scoped-zero", r"(?:\C){0}a", 0),
    ("c-define", r"(?(DEFINE)(?<x>\C))a", 0),
    ("c-unreachable", r"(?!)\C", 0),
    ("c-alternative", r"a|\C", 0),
    ("c-mixed-j", r"(?J:\C{0})", 0),
    ("c-mixed-unset-j", r"(?-J:\C{0})", 0),
    ("c-quoted", r"\Q\C\E", 0),
    ("c-escaped", r"\\C", 0),
    ("c-comment", r"(?#\C)a", 0),
    ("c-extended-comment", "(?x)# \\C\na", 0),
    ("c-callout", r"(?C'\C')a", 0),
    ("c-mark", r"(*MARK:\C)a", 0),
    ("c-literal", r"\C{0}", LITERAL),
    ("c-class-invalid", r"[\C]", 0),
    ("c-never-invalid", r"\C", NEVER_C),
    ("c-never-zero-invalid", r"\C{0}", NEVER_C),
    ("c-following-invalid", r"\C(", 0),
]
commands, rows = [], []
for width in (8, 16):
    cases = []
    for utf in (False, True):
        for name, pattern, flags in seeds:
            id = f"{name}-{width}-{'utf' if utf else 'raw'}"
            units = list(pattern.encode("utf-8")) if width == 8 else [ord(c) for c in pattern]
            flags |= UTF if utf else 0
            rows.append(dict(id=id, width=width, pattern=pattern, units=units, flags=flags))
            cases.append((f"units_{len(cases)}", id, units, flags))
    header = ["/* Original supplementary inputs; generated by probe-c.py. */",
              "struct probe { const char *id; const PCRE2_UCHAR *units; size_t length; uint32_t flags; };"]
    for symbol, id, units, flags in cases:
        header.append(f"static const PCRE2_UCHAR {symbol}[] = {{{','.join(map(str, units+[0]))}}};")
    header.append("static const struct probe cases[] = {")
    for symbol, id, units, flags in cases:
        header.append(f'{{"{id}",{symbol},{len(units)},{flags}u}},')
    header.append("};")
    (HERE / f"native-c-cases-{width}.h").write_text("\n".join(header)+"\n")
    executable = TEMP / f"probe-c-{width}"
    command = ["clang", "-O2", f"-DPCRE2_CODE_UNIT_WIDTH={width}",
               "-I", str(TEMP / "native-build"), "-I", str(HERE),
               str(HERE / "native-c-probe.c"),
               str(TEMP / f"native-build/libpcre2-{width}.a"), "-o", str(executable)]
    subprocess.run(command, check=True)
    output = subprocess.run([str(executable)], capture_output=True, text=True, check=True)
    (REPORT / f"native-c-{width}.jsonl").write_text(output.stdout)
    commands.extend([command, [str(executable)]])
(REPORT / "native-c-inputs.json").write_text(json.dumps(rows, indent=2)+"\n")
for path in [*REPORT.iterdir(), *HERE.iterdir()]:
    if (path.name.startswith("native-c-") and path.name != "native-c-provenance.json") or path.name in ("probe-c.py", "source-c-witness.txt"):
        hashes[str(path.relative_to(Path.cwd()) if path.is_absolute() else path)] = digest(path.read_bytes())
(REPORT / "native-c-provenance.json").write_text(json.dumps(dict(
    source_commit="b2bd4254b379b9d7dc9a3dda060a7e27009ccdff",
    scope=f"{len(rows)} supplementary correctness-only compilations; no prior J replay, native rebuild or measurement.",
    commands=commands, sha256=hashes), indent=2)+"\n")
print(f"Retained {len(rows)} independent supplementary HASBACKSLASHC observations.")

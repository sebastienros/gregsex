"""Bounded JCHANGED oracle intake from previously verified PCRE2 static libraries.

No production matcher, native rebuild, timing, or managed-derived expectations.
Run from the repository root: python3 tools/oracles/pcre2/option-metadata/probe.py
"""
import hashlib
import json
from pathlib import Path
import subprocess
import tarfile

REPORT = Path("test/corpora/pcre2/option-metadata")
HERE = Path(__file__).resolve().parent
TEMP = Path("/private/tmp/gregsex-m5-option-metadata-native")
TEMP.mkdir(parents=True, exist_ok=True)
receipt = json.loads(Path("test/corpora/pcre2/controls/native-window-provenance.json").read_text())
hashes = {}

def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

archive = Path(receipt["archive"])
assert digest(archive) == receipt["archiveSha256"]
hashes[str(archive)] = digest(archive)
with tarfile.open(archive) as tar:
    for row in receipt["members"]:
        data = tar.extractfile(row["member"]).read()
        assert len(data) == row["bytes"]
        assert hashlib.sha256(data).hexdigest() == row["sha256"]
        path = TEMP / row["member"]
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        hashes[row["member"]] = digest(path)

source = Path("tools/oracles/pcre2/source/pcre2-10.46-source.tar.gz")
assert digest(source) == "ffde0c6ead457c4f8edcd8f9ce490bbabd30adabdfd179ecaddd320946cf3872"
hashes[str(source)] = digest(source)
with tarfile.open(source) as tar:
    member = "pcre2-pcre2-10.46/src/pcre2_compile.c"
    data = tar.extractfile(member).read()
    hashes[member] = hashlib.sha256(data).hexdigest()
    lines = data.decode().splitlines()
    (REPORT / "source-witness.txt").write_text("\n".join(
        f"{i + 1}: {lines[i]}" for i in range(4974, 4978)) + "\n")

# IDs and inputs are selected from source grammar before executing GregsEx.
# All patterns are valid in four domains unless explicitly testing rejection.
DUPNAMES = 0x40
UTF = 0x80000
LITERAL = 0x2000000
seeds = [
    ("empty", "", 0), ("initial-dupnames", "a", DUPNAMES),
    ("set", "(?J)a", 0), ("redundant-set", "(?J)a", DUPNAMES),
    ("unset", "(?-J)a", DUPNAMES), ("redundant-unset", "(?-J)a", 0),
    ("set-unset", "(?J-J)a", 0), ("unset-set", "(?-J)(?J)a", 0),
    ("repeated", "(?JJ)a", 0), ("only-set", "(?J)", 0),
    ("only-unset", "(?-J)", 0), ("scoped-empty", "(?J:)", 0),
    ("scoped-unset-empty", "(?-J:)", 0),
    ("scoped-zero", "(?J:a){0}b", 0),
    ("scoped-unset-zero", "(?-J:a){0}b", DUPNAMES),
    ("define", "(?(DEFINE)(?J:(?<x>a)))b", 0),
    ("define-unset", "(?(DEFINE)(?-J:(?<x>a)))b", DUPNAMES),
    ("alternative", "a|(?J)b", 0),
    ("nested-scope", "(?J:(?-J:a))b", 0),
    ("reset-plus-j", "(?^J)a", 0), ("reset-without-j", "(?^)a", DUPNAMES),
    ("other-options", "(?imn-sx)a", 0),
    ("mixed-options", "(?imJ-sx:a)", 0),
    ("directives", "(*CRLF)(*NO_START_OPT)(?J:a)", 0),
    ("utf-directive", "(*UTF)(?-J:a)", 0),
    ("duplicate-names-initial", "(?<x>a)(?<x>b)", DUPNAMES),
    ("duplicate-names-inline", "(?J)(?<x>a)(?<x>b)", 0),
    ("ordinary-j", "J", 0), ("class-j", "[J(?J)]", 0),
    ("quoted-j", r"\Q(?J)\E", 0), ("escaped-j", r"\(\?J\)", 0),
    ("comment-j", "(?#(?J)a", 0),
    ("extended-comment-j", "(?x)# (?J)\na", 0),
    ("callout-j", "(?C'(?J)')a", 0), ("mark-j", "(*MARK:(?J)a", 0),
    ("literal-j", "(?J)", LITERAL),
    ("bad-option-after-j", "(?Jq)a", 0),
    ("missing-close", "(?J", 0), ("missing-scoped-close", "(?J:a", 0),
    ("duplicate-unset", "(?-J)(?<x>a)(?<x>b)", DUPNAMES),
]
rows = []
commands = []
for width in (8, 16):
    cases = []
    for utf in (False, True):
        for name, pattern, flags in seeds:
            id = f"{name}-{width}-{'utf' if utf else 'raw'}"
            units = list(pattern.encode("utf-8")) if width == 8 else [ord(c) for c in pattern]
            flags |= UTF if utf else 0
            rows.append(dict(id=id, width=width, pattern=pattern, units=units, flags=flags))
            symbol = f"units_{len(cases)}"
            cases.append((symbol, id, units, flags))
    header = ["/* Original bounded test inputs; generated by probe.py. */",
              "struct probe { const char *id; const PCRE2_UCHAR *units; size_t length; uint32_t flags; };"]
    for symbol, id, units, flags in cases:
        header.append(f"static const PCRE2_UCHAR {symbol}[] = {{{','.join(map(str, units + [0]))}}};")
    header.append("static const struct probe cases[] = {")
    for symbol, id, units, flags in cases:
        header.append(f'{{"{id}",{symbol},{len(units)},{flags}u}},')
    header.append("};")
    hpath = HERE / f"native-cases-{width}.h"
    hpath.write_text("\n".join(header) + "\n")
    executable = TEMP / f"probe-{width}"
    command = ["clang", "-O2", f"-DPCRE2_CODE_UNIT_WIDTH={width}",
               "-I", str(TEMP / "native-build"), "-I", str(HERE),
               str(HERE / "native-probe.c"),
               str(TEMP / f"native-build/libpcre2-{width}.a"), "-o", str(executable)]
    subprocess.run(command, check=True)
    output = subprocess.run([str(executable)], capture_output=True, text=True, check=True)
    (REPORT / f"native-{width}.jsonl").write_text(output.stdout)
    commands.extend([command, [str(executable)]])

(REPORT / "native-inputs.json").write_text(json.dumps(rows, indent=2) + "\n")
for path in [*REPORT.iterdir(), *HERE.iterdir()]:
    if path.suffix in (".c", ".h", ".py", ".jsonl") or path.name in ("source-witness.txt", "native-inputs.json"):
        hashes[str(path.relative_to(Path.cwd()) if path.is_absolute() else path)] = digest(path)
(REPORT / "native-provenance.json").write_text(json.dumps(dict(
    source_commit="b2bd4254b379b9d7dc9a3dda060a7e27009ccdff",
    scope=f"{len(rows)} bounded correctness-only compilations; cached libraries; no matcher, native rebuild or measurements.",
    commands=commands, sha256=hashes), indent=2) + "\n")
print(f"Retained {len(rows)} independent native JCHANGED observations.")
